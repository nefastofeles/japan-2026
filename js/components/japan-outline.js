/**
 * Hand-simplified Japan for the family map.
 *
 * Equirectangular maps make Hokkaido too wide. We shrink longitude by
 * cos(38°) so the islands keep the slim kite people recognise from
 * postcards and weather maps.
 *
 * Rings are the four main islands plus Awaji (the comma in the Inland
 * Sea). Okinawa is left off: pulling the camera that far south would
 * shrink Honshu into a blob, and this trip never goes there.
 */

const LNG_WEST = 129.25;
const LNG_EAST = 145.95;
const LAT_SOUTH = 30.95;
const LAT_NORTH = 45.55;
const COS = Math.cos((38 * Math.PI) / 180);

export const MAP_VIEWBOX = "0 0 640 760";

export function project(lng, lat) {
  const padX = 40;
  const padY = 28;
  const innerW = 640 - padX * 2;
  const innerH = 760 - padY * 2;
  const xNorm = (lng - LNG_WEST) * COS;
  const xMax = (LNG_EAST - LNG_WEST) * COS;
  const yNorm = LAT_NORTH - lat;
  const yMax = LAT_NORTH - LAT_SOUTH;
  return [
    Math.round((padX + (xNorm / xMax) * innerW) * 10) / 10,
    Math.round((padY + (yNorm / yMax) * innerH) * 10) / 10,
  ];
}

function ring(lngLats) {
  return lngLats.map(([lng, lat]) => project(lng, lat));
}

